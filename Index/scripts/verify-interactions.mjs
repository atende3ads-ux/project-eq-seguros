import assert from 'node:assert/strict'
import { chromium } from 'playwright'
const browser = await chromium.launch({ headless: true })
try {
  const desktop = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  const errors = []
  desktop.on('pageerror', (err) => errors.push(err.message))
  await desktop.goto('http://localhost:3000/', { waitUntil: 'networkidle' })
  const menu = desktop.locator('.has-dd').first()
  await menu.hover()
  await desktop.waitForTimeout(250)
  assert.ok((await menu.getAttribute('class')).includes('open'))
  await desktop.goto('http://localhost:3000/cases', { waitUntil: 'networkidle' })
  await desktop.locator('button[data-seg="varejo"]').click()
  assert.equal(await desktop.locator('.casecard:visible').count(), 1)
  await desktop.locator('.casecard:visible').click()
  await desktop.waitForURL('**/case?c=*')
  assert.ok((await desktop.locator('h1').innerText()).includes('checkout'))
  const invalid = await desktop.goto('http://localhost:3000/case?c=inexistente', { waitUntil: 'networkidle' })
  assert.equal(invalid.status(), 404)
  const missing = await desktop.goto('http://localhost:3000/pagina-inexistente', { waitUntil: 'networkidle' })
  assert.equal(missing.status(), 404)
  const redirect = await desktop.request.get('http://localhost:3000/contato.html', { maxRedirects: 0 })
  assert.equal(redirect.status(), 308)
  assert.ok(redirect.headers().location.endsWith('/contato'))
  const home = await desktop.request.get('http://localhost:3000/')
  assert.equal(home.headers()['x-robots-tag'], 'noindex, nofollow')
  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 } })
  mobile.on('pageerror', (err) => errors.push(err.message))
  await mobile.goto('http://localhost:3000/', { waitUntil: 'networkidle' })
  await mobile.locator('#burger').click()
  assert.ok((await mobile.locator('#menu').getAttribute('class')).includes('open'))
  await mobile.locator('.has-dd .nav-top').first().click()
  assert.ok((await mobile.locator('.has-dd').first().getAttribute('class')).includes('open'))
  assert.deepEqual(errors, [], 'Não deve haver erros de execução ou hidratação no navegador.')
  console.log('PASS: dropdown desktop, filtro de cases, detalhe, 404, redirecionamento, noindex e menu mobile; sem erros de hidratação.')
} finally { await browser.close() }
